// Builds ASSET_PACKS.md and LESSGO_INVENTORY.md from scan-assets.mjs output.
// Usage: node scan-assets.mjs > scan.json && node make-asset-doc.mjs scan.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const scan = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const byId = new Map(scan.map(i => [i.id, i]));

// Packs chosen for the editor playset (all compiled .cok, no EAI dependency).
const OBJECT_PACKS = ["140176", "146553", "137334", "132403", "134056", "146871", "159309", "159384", "134147", "132771"];
const SURFACE_PACKS = ["148077", "144834", "144550", "143898"];
const OPTIONAL_PACKS = { "132923": "farm-field surfaces (Agriculture surface pack)", "148605": "flowering shrub (Tecoma stans)" };

const dims = b => b ? [b[3] - b[0], b[5] - b[2], b[4] - b[1]] : null; // W(x), D(z), H(y)
const fmt = d => d ? `${d[0].toFixed(1)} × ${d[1].toFixed(1)} × ${d[2].toFixed(1)}` : "–";

function objCategory(p) {
  const d = dims(p.bounds), n = p.name;
  if (/rock|cliff|boulder/i.test(n)) {
    const ext = d ? Math.max(d[0], d[1]) : 0;
    if (/Cliff(Side|Slim|Stack|FreeStanding|Tall)/i.test(n) || ext > 60) return "cliff";
    if (ext > 20) return "boulder";
    if (ext > 8) return "rock large";
    if (ext > 3) return "rock medium";
    return "rock small";
  }
  if (/grass/i.test(n)) return d && d[2] < 1.5 ? "grass tuft" : "tall grass";
  if (/fern/i.test(n)) return "other (fern)";
  if (/undergrowth/i.test(n)) return "other (undergrowth)";
  if (/flower|bloom/i.test(n)) return "other (flower)";
  return "other";
}
function surfCategory(n) {
  if (/riverbed/i.test(n)) return "surface riverbed";
  if (/pebble/i.test(n)) return "surface pebbles";
  if (/crack/i.test(n) && !/sand/i.test(n)) return "surface dirt/soil";
  if (/grass|meadow|lawn/i.test(n)) return "surface grass";
  if (/rock|stone|cliff|gravel/i.test(n)) return "surface rock/stone";
  if (/mud/i.test(n)) return "surface mud";
  if (/soil|dirt|ground|earth|field|farm/i.test(n)) return "surface dirt/soil";
  if (/sand/i.test(n)) return "surface sand";
  if (/asphalt|concrete|tile/i.test(n)) return "surface paved";
  return "surface other";
}

function packCategory(i) {
  const objs = i.prefabs.filter(p => p.type === "StaticObjectPrefab");
  const surf = i.prefabs.filter(p => p.type === "SurfacePrefab").length;
  const plants = objs.filter(p => p.comps.some(c => c === "PlantObject" || c === "TreeObject")).length;
  const rocks = objs.filter(p => /rock|cliff|boulder/i.test(p.name)).length;
  const decals = objs.filter(p => p.meshComps.includes("DecalProperties") || /decal/i.test(p.name)).length;
  const buildings = i.prefabs.filter(p => /Building/.test(p.type)).length;
  if (i.eaiLoose.some(d => /decal/i.test(d))) return "decals";
  if (i.eaiLoose.some(d => /surface/i.test(d))) return "surfaces";
  if (i.eaiLoose.some(d => /netlane/i.test(d))) return "net lanes";
  if (!i.prefabs.length) return i.hasDll ? "code mod" : (i.tags.includes("Map") ? "map" : "other");
  if (rocks && rocks >= objs.length / 2 && !buildings) return "rocks/cliffs";
  if (plants && plants >= objs.length / 2 && !buildings) return /tree|fir|oak|pine|maple|palm|birch/i.test(i.name) ? "trees" : "grass/vegetation";
  if (surf && surf >= objs.length && !buildings) return "surfaces";
  if (decals && decals >= objs.length / 2 && !buildings) return "decals (signage/branding)";
  if (buildings) return "buildings";
  return "props/other";
}

const esc = s => String(s ?? "").replace(/\|/g, "\\|");
const q = s => "`" + String(s).replace(/`/g, "") + "`";
const count = {};
const add = c => (count[c] = (count[c] || 0) + 1);

let md = `# Asset packs from lessgo-withEAI for the Dakota Falls import

Generated by \`make-asset-doc.mjs\` from \`scan-assets.mjs\`. The scan read every \`.Prefab\` entry inside each pack's \`.cok\` bundle (a zip) under \`.cache\\Mods\\pdx_mods\\<id>_<ver>\`.

- **Prefab names** are the prefab's internal \`name\` field, which is what the prefab system resolves; display names come from the bundle's \`en-US.loc\`. Names are exact, including spaces and the \`(Styx's)\` suffixes. Watch \`pd Long Grass Prop \`, which has a **trailing space**.
- **Footprint** is W × D × H in metres (x, z, y), taken from the bounds of the prefab's main mesh (LOD0). Area surfaces have no footprint.
- **EAI rule:** a pack counts as *EAI-required* if it declares ExtraAssetsImporter (80529) as a dependency or ships loose \`CustomDecals/\`, \`CustomSurfaces/\`, \`CustomNetLanes/\`, \`Decals/\` or \`Surfaces/\` folders (JSON + textures) instead of \`.cok\` prefabs. All packs below are compiled \`.cok\` with empty \`package.deps\` and no mod dependencies.
- **No dirt, mud, tyre-mark or stain decal pack works without EAI.** Every such pack in lessgo-withEAI is EAI-based (see the end of this file). The closest compiled substitutes are the dirt/soil/rock/grass **area surfaces** listed under "Surface packs". They are polygons, not point objects, so they belong in the bridge's surfaces import rather than object placement.

## Packs selected (no EAI needed)

| id | Pack | Folder | Kind | Placeable names |
|---|---|---|---|---|
`;
for (const id of [...OBJECT_PACKS, ...SURFACE_PACKS]) {
  const i = byId.get(id);
  const n = i.prefabs.filter(p => p.type === (SURFACE_PACKS.includes(id) ? "SurfacePrefab" : "StaticObjectPrefab") && (SURFACE_PACKS.includes(id) || objCategory(p) !== "other")).length;
  md += `| ${id} | ${esc(i.name)} | ${i.dir} | ${SURFACE_PACKS.includes(id) ? "area surfaces" : packCategory(i)} | ${n} |\n`;
}

md += `\n## Object packs (point placement)\n`;
for (const id of OBJECT_PACKS) {
  const i = byId.get(id);
  let rows = i.prefabs.filter(p => p.type === "StaticObjectPrefab").map(p => ({ p, cat: objCategory(p) }));
  const skipped = rows.filter(r => r.cat === "other");
  rows = rows.filter(r => r.cat !== "other").sort((a, b) => a.p.name.localeCompare(b.p.name));
  md += `\n### ${esc(i.name)} (${id}, ${i.dir})\n\n| Prefab name | Display name | Category | Footprint W×D×H m | Notes |\n|---|---|---|---|---|\n`;
  for (const { p, cat } of rows) {
    add(cat);
    const notes = [p.comps.includes("TreeObject") ? "TreeObject (has growth stages)" : p.comps.includes("PlantObject") ? "PlantObject" : "",
      p.display ? "" : "no display name in .loc"].filter(Boolean).join("; ");
    md += `| ${q(p.name)} | ${esc(p.display || "–")} | ${cat} | ${fmt(dims(p.bounds))} | ${notes} |\n`;
  }
  if (skipped.length) md += `\nAlso in this pack, not nature: ${skipped.map(r => q(r.p.name)).join(", ")}.\n`;
}

md += `\n## Surface packs (area polygons, substitute for dirt/mud decals)\n`;
for (const id of SURFACE_PACKS) {
  const i = byId.get(id);
  const rows = i.prefabs.filter(p => p.type === "SurfacePrefab").map(p => ({ p, cat: surfCategory(p.name + " " + (p.display || "")) }))
    .sort((a, b) => a.cat.localeCompare(b.cat) || a.p.name.localeCompare(b.p.name));
  md += `\n### ${esc(i.name)} (${id}, ${i.dir})\n\n| Prefab name | Display name | Category |\n|---|---|---|\n`;
  for (const { p, cat } of rows) {
    add(cat);
    md += `| ${q(p.name)} | ${p.display && p.display !== p.name ? esc(p.display) : "(same)"} | ${cat} |\n`;
  }
}

md += `\n## Counts of prefab names by category\n\n| Category | Names |\n|---|---|\n`;
for (const [c, n] of Object.entries(count).sort()) md += `| ${c} | ${n} |\n`;

md += `\n## Optional, not added to the playset\n\n`;
for (const [id, why] of Object.entries(OPTIONAL_PACKS)) md += `- ${id} ${esc(byId.get(id).name)}: ${why}. Compiled, no EAI.\n`;
md += `- Trees, cacti and planter props (Cardon Cactus 140402, Douglas Fir 159752, Grass Planters 144515, Raised Curbs and Planters 130495, Plaza Planters 148938) are compiled too but are not grass, rock or decal.
- NA Basic Detailing Pack 138899 has compiled decals, but they are urban sidewalk and sign decals, not dirt.

## EAI-required packs (excluded)\n\n| id | Pack | Category | Reason |\n|---|---|---|---|\n`;
for (const i of scan.filter(i => i.eaiRequired)) {
  const why = [i.deps.includes("80529") ? "depends on 80529" : "", i.eaiLoose.length ? "loose " + i.eaiLoose.join("/") : ""].filter(Boolean).join(", ");
  md += `| ${i.id} | ${esc(i.name)} | ${packCategory(i)} | ${why} |\n`;
}
md += `\nThe full inventory of all ${scan.length} lessgo-withEAI items is in [LESSGO_INVENTORY.md](LESSGO_INVENTORY.md).\n`;
fs.writeFileSync(path.join(here, "ASSET_PACKS.md"), md);

let inv = `# lessgo-withEAI inventory (${scan.length} items)\n\nGenerated by \`make-asset-doc.mjs\`. Folder = \`.cache\\Mods\\pdx_mods\\<folder>\`. EAI = needs ExtraAssetsImporter (80529).\n\n| id | Name | Folder | Enabled | Category | EAI | Prefabs |\n|---|---|---|---|---|---|---|\n`;
for (const i of [...scan].sort((a, b) => packCategory(a).localeCompare(packCategory(b)) || Number(a.id) - Number(b.id)))
  inv += `| ${i.id} | ${esc((i.name || "").trim())} | ${i.dir} | ${i.enabled ? "yes" : "no"} | ${packCategory(i)} | ${i.eaiRequired ? "EAI" : ""} | ${i.prefabs.length} |\n`;
fs.writeFileSync(path.join(here, "LESSGO_INVENTORY.md"), inv);
console.log(JSON.stringify(count));
