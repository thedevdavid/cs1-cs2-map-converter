md.push(`In-game export: \`${path.basename(base)}\` (DakotaExport, PO schema \`${game.schema}\`). Offline: \`cs1-offline/out\` from the Workshop map .crp. Generated by \`node cs1-offline/src/crosscheck.mjs\`.`, '');
md.push('## 1. Procedural Objects', '');
md.push('| check | result |', '|---|---|');
md.push(`| objects | in-game ${game.objects.length}, offline ${mine.objects.length}, matched by id ${game.objects.length - extra.length}, in-game only ${extra.length} |`);
md.push(`| offline only (did not load in game) | ${missing.length}: ${Object.entries(missingClasses).map(([k, v]) => `${k} ${v}`).join(', ')} |`);
md.push(`| = the offline \`loadsInPlayset: false\` set | ${missingEqualsNotLoading ? 'yes, exactly (all base prefab `1094334744.Cube_Data`)' : 'NO'} |`);
md.push(`| in-game "failed container" meshes (kind 1) | ${failedMeshIds.length}; same ids as the missing objects: ${failedEqualsMissing ? 'yes' : 'no'} |`);
md.push(`| position, |Δ| | max ${f2(Math.max(...dPos), 6)} m, p99 ${f2(pct(dPos, 0.99), 6)} m |`);
md.push(`| rotation, angle between quaternions | max ${f2(Math.max(...dRot), 4)}°, p99 ${f2(pct(dRot, 0.99), 4)}° |`);
md.push(`| vertex count | ${vMismatch.length} mismatches${vMismatch.length ? ': ' + vMismatch.slice(0, 10).join('; ') : ''} |`);
md.push(`| triangle count (vs full in-game mesh) | ${tMismatch.length} mismatches of ${boxN}${tMismatch.length ? ': ' + tMismatch.slice(0, 10).join('; ') : ''} |`);
md.push(`| world bounding box (full in-game mesh vs offline full mesh), max per-axis |Δ| | max ${f2(Math.max(...dBox), 3)} m, p99 ${f2(pct(dBox, 0.99), 3)} m, median ${f2(pct(dBox, 0.5), 4)} m over ${boxN} objects (worst: ${boxWorst.slice(0, 3).map(([d, id]) => `${id} ${f2(d, 3)} m`).join(', ')}) |`);
md.push(`| objects without a live in-game mesh entry (mesh unchanged, meshStatus 1) | ${game.objects.length - boxN} (compared by position, rotation and vertex count only) |`);
md.push('');

// ---------- 2. height rasters ----------
function readPng16(file) {
  const b = fs.readFileSync(file); let p = 8, w, h; const idat = [];
  while (p < b.length) { const len = b.readUInt32BE(p), t = b.toString('latin1', p + 4, p + 8), d = b.subarray(p + 8, p + 8 + len); p += 12 + len; if (t === 'IHDR') { w = d.readUInt32BE(0); h = d.readUInt32BE(4); } else if (t === 'IDAT') idat.push(d); else if (t === 'IEND') break; }
  const raw = zlib.inflateSync(Buffer.concat(idat)), stride = w * 2, out = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1)), cur = out.subarray(y * stride, (y + 1) * stride), prev = y ? out.subarray((y - 1) * stride, y * stride) : Buffer.alloc(stride);
    for (let x = 0; x < stride; x++) { const a = x >= 2 ? cur[x - 2] : 0, up = prev[x], c = x >= 2 ? prev[x - 2] : 0; let v = src[x];
      if (f === 1) v += a; else if (f === 2) v += up; else if (f === 3) v += (a + up) >> 1; else if (f === 4) { const q = a + up - c, pa = Math.abs(q - a), pb = Math.abs(q - up), pc = Math.abs(q - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? up : c; } cur[x] = v & 255; }
  }
  const px = new Uint16Array(w * h); for (let i = 0; i < w * h; i++) px[i] = out.readUInt16BE(2 * i);
  return { w, h, px };
}
const G = readPng16(`${base}-po-heights.png`), M = readPng16(path.join(outDir, 'po-offline-heights.png'));
function cmp(flip) {
  const d = []; let both = 0, onlyG = 0, onlyM = 0;
  for (let r = 0; r < 1081; r++) for (let c = 0; c < 1081; c++) {
    const a = G.px[r * 1081 + c], b = M.px[(flip ? 1080 - r : r) * 1081 + c];
    if (a && b) { both++; d.push(Math.abs(a - b) / 64); } else if (a) onlyG++; else if (b) onlyM++;
  }
  return { both, onlyG, onlyM, max: Math.max(...d), p99: pct(d, 0.99), p50: pct(d, 0.5), exact: d.filter(x => x < 1 / 64).length };
}
const same = cmp(false), flipped = cmp(true);
// which objects own the cells that differ (from the JSON cell owners)
const gj = JSON.parse(fs.readFileSync(`${base}-po-heights.json`, 'utf8'));
const mj = JSON.parse(fs.readFileSync(path.join(outDir, 'po-offline-heights.json'), 'utf8'));
const gOwner = new Map(); for (let i = 0; i < gj.cells.length; i += 4) { const idx = gj.cells[i], row = Math.floor(idx / 1081), col = idx % 1081; gOwner.set((1080 - row) * 1081 + col, [gj.cells[i + 1], gj.cells[i + 3]]); }   // their JSON is row 0 = south
const mOwner = new Map(mj.cells.map(c => [c[0], [c[1], c[3]]]));
let ownerDiff = 0, ownerSameDiff = [], jsonDiff = [];
for (const [i, [gy, gid]] of gOwner) { const m = mOwner.get(i); if (!m) continue; jsonDiff.push(Math.abs(gy - m[0])); if (gid !== m[1]) ownerDiff++; else ownerSameDiff.push(Math.abs(gy - m[0])); }
const classOf = new Map(mine.objects.map(o => [o.id, `${o.class}/${o.subClass}`]));
const onlyGameCls = {}, onlyMineCls = {};
for (const [i, [, gid]] of gOwner) if (!mOwner.has(i)) { const k = classOf.get(gid) ?? '?'; onlyGameCls[k] = (onlyGameCls[k] ?? 0) + 1; }
for (const [i, [, mid]] of mOwner) if (!gOwner.has(i)) { const k = classOf.get(mid) ?? '?'; onlyMineCls[k] = (onlyMineCls[k] ?? 0) + 1; }
md.push('## 2. PO height rasters (1081 frame, value = metres × 64)', '');
md.push('| check | result |', '|---|---|');
md.push(`| cells | in-game ${gj.coveredCells}, offline ${mj.cellCount}; both non-zero ${same.both} |`);
md.push(`| PNG, as stored (both row 0 = north) | max |Δ| ${f2(same.max)} m, p99 ${f2(same.p99)} m, median ${f2(same.p50, 3)} m; identical value in ${same.exact} of ${same.both} cells |`);
md.push(`| PNG, offline flipped north-south (orientation test) | max |Δ| ${f2(flipped.max)} m, p99 ${f2(flipped.p99)} m, both non-zero only ${flipped.both} → orientation agrees as stored |`);
md.push(`| scale | both encode metres × 64 (in-game JSON maxY × 64 = its PNG value); the in-game JSON indexes rows from the south (\`rowAxis +z\`), the PNGs from the north |`);
md.push(`| JSON maxY, cells in both | max |Δ| ${f2(Math.max(...jsonDiff))} m, p99 ${f2(pct(jsonDiff, 0.99))} m; same owning object in ${jsonDiff.length - ownerDiff} cells, where max |Δ| ${f2(Math.max(...ownerSameDiff))} m, p99 ${f2(pct(ownerSameDiff, 0.99), 3)} m |`);
md.push(`| cells only in-game, by owner class | ${Object.entries(onlyGameCls).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'} |`);
md.push(`| cells only offline, by owner class | ${Object.entries(onlyMineCls).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'} |`);
// replicate both rasterisation rules on the in-game full meshes (identical geometry, see section 1)
{
  const N = 1081, tri = new Float32Array(N * N).fill(-1e9), vtx = new Float32Array(N * N).fill(-1e9), edg = new Float32Array(N * N).fill(-1e9);
  const gx = x => (x + 8640) / 16, gz = z => (8640 - z) / 16;
  const put = (A, x, z, y) => { const c = Math.round(gx(x)), r = Math.round(gz(z)); if (r >= 0 && c >= 0 && r < N && c < N && y > A[r * N + c]) A[r * N + c] = y; };
  const b = fs.readFileSync(`${base}-po-meshes.bin`); let p = 12;
  while (p < b.length) {
    const kind = b.readInt32LE(p + 4), n = b.readInt32LE(p + 8); p += 12;
    const V = new Float32Array(n * 3); for (let i = 0; i < n * 3; i++) V[i] = b.readFloatLE(p + 4 * i); p += 12 * n;
    const ti = b.readInt32LE(p); p += 4; const T = new Int32Array(ti); for (let i = 0; i < ti; i++) T[i] = b.readInt32LE(p + 4 * i); p += 4 * ti;
    const uv = b.readInt32LE(p); p += 4 + 8 * uv;
    if (kind !== 0) continue;
    for (let t = 0; t + 2 < ti; t += 3) {
      const [a, bb, c] = [T[t] * 3, T[t + 1] * 3, T[t + 2] * 3];
      const ax = gx(V[a]), az = gz(V[a + 2]), bx = gx(V[bb]), bz = gz(V[bb + 2]), cx = gx(V[c]), cz = gz(V[c + 2]);
      const den = (bz - cz) * (ax - cx) + (cx - bx) * (az - cz);
      if (Math.abs(den) > 1e-12)
        for (let r = Math.max(0, Math.ceil(Math.min(az, bz, cz))); r <= Math.min(N - 1, Math.floor(Math.max(az, bz, cz))); r++)
          for (let col = Math.max(0, Math.ceil(Math.min(ax, bx, cx))); col <= Math.min(N - 1, Math.floor(Math.max(ax, bx, cx))); col++) {
            const l1 = ((bz - cz) * (col - cx) + (cx - bx) * (r - cz)) / den, l2 = ((cz - az) * (col - cx) + (ax - cx) * (r - cz)) / den, l3 = 1 - l1 - l2;
            if (l1 < -1e-4 || l2 < -1e-4 || l3 < -1e-4) continue;
            const y = l1 * V[a + 1] + l2 * V[bb + 1] + l3 * V[c + 1], i = r * N + col;
            if (y > tri[i]) tri[i] = y;
          }
      for (const [u, v] of [[a, bb], [bb, c], [c, a]]) {   // exporter: a point every 4 m along each edge (xz length)
        const len = Math.hypot(V[v] - V[u], V[v + 2] - V[u + 2]), steps = Math.min(4096, Math.ceil(len / 4));
        for (let s = 1; s < steps; s++) { const f = s / steps; put(edg, V[u] + (V[v] - V[u]) * f, V[u + 2] + (V[v + 2] - V[u + 2]) * f, V[u + 1] + (V[v + 1] - V[u + 1]) * f); }
      }
    }
    for (let i = 0; i < n; i++) put(vtx, V[3 * i], V[3 * i + 2], V[3 * i + 1]);
  }
  const vs = (ref, f) => { const d = []; for (const [i, [y]] of ref) { const v = f(i); if (v > -1e8) d.push(Math.abs(v - y)); } return `median ${f2(pct(d, 0.5), 3)} m, p99 ${f2(pct(d, 0.99), 3)} m`; };
  const triOnly = i => tri[i], triVtx = i => Math.max(tri[i], vtx[i]), triVtxEdge = i => Math.max(tri[i], vtx[i], edg[i]);
  md.push('', 'Why the rasters differ: the geometry is identical (section 1), the sampling rule is not. Replicated on the in-game full meshes:', '');
  md.push('| rule (1081 grid, 16 m) | vs in-game raster | vs offline v1 raster |', '|---|---|---|');
  md.push(`| triangles at sample points only | ${vs(gOwner, triOnly)} | ${vs(mOwner, triOnly)} |`);
  md.push(`| + every vertex snapped to the nearest sample (offline v1) | ${vs(gOwner, triVtx)} | ${vs(mOwner, triVtx)} |`);
  md.push(`| + a point every 4 m along every edge, snapped (in-game exporter, \`PoGeometry.cs\`) | ${vs(gOwner, triVtxEdge)} | ${vs(mOwner, triVtxEdge)} |`);
  md.push('', 'So each raster equals its own rule applied to the same meshes (the residue is the 6 unedited objects and the effect emitters, which are not in the mesh file). Orientation and scale agree. Snapping vertices or edge points to the nearest 16 m sample lifts cells on steep flanks by up to hundreds of metres (the hm-rebuild "columns"), so **v2 uses triangles only** (vertices only for objects that cover no sample). The PNGs clip at 1 024 m (× 64); the JSON values do not.', '');
}

