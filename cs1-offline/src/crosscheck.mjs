const mine = JSON.parse(fs.readFileSync(path.join(outDir, 'po-offline.json'), 'utf8'));
// full-resolution world meshes from -po-meshes.bin
const meshes = new Map();
{
  const b = fs.readFileSync(`${base}-po-meshes.bin`);
  if (b.toString('latin1', 0, 8) !== 'DKPOMSH1') throw new Error('bad mesh file');
  let p = 12;
  while (p < b.length) {
    const id = b.readInt32LE(p), kind = b.readInt32LE(p + 4), n = b.readInt32LE(p + 8); p += 12;
    const mn = [Infinity, Infinity, Infinity], mx = [-Infinity, -Infinity, -Infinity];
    for (let i = 0; i < n; i++) for (let k = 0; k < 3; k++) { const v = b.readFloatLE(p + 12 * i + 4 * k); if (v < mn[k]) mn[k] = v; if (v > mx[k]) mx[k] = v; }
    p += 12 * n;
    const ti = b.readInt32LE(p); p += 4 + 4 * ti;
    const uv = b.readInt32LE(p); p += 4 + 8 * uv;
    meshes.set(id, { kind, n, tris: ti / 3, mn, mx });
  }
}
const gById = new Map(game.objects.map(o => [o.id, o]));
const mById = new Map(mine.objects.map(o => [o.id, o]));
const missing = mine.objects.filter(o => !gById.has(o.id));
const extra = game.objects.filter(o => !mById.has(o.id));
const missingClasses = {};
for (const o of missing) { const k = `${o.class}/${o.subClass}`; missingClasses[k] = (missingClasses[k] ?? 0) + 1; }
const notLoadingIds = new Set(mine.objects.filter(o => !o.loadsInPlayset).map(o => o.id));
const missingEqualsNotLoading = missing.length === notLoadingIds.size && missing.every(o => notLoadingIds.has(o.id));
const failedMeshIds = [...meshes].filter(([, m]) => m.kind === 1).map(([id]) => id);
const failedEqualsMissing = failedMeshIds.length === missing.length && failedMeshIds.every(id => notLoadingIds.has(id));

const dPos = [], dRot = [], dBox = [], vMismatch = [], tMismatch = [], boxWorst = [];
let boxN = 0;
for (const g of game.objects) {
  const m = mById.get(g.id); if (!m) continue;
  dPos.push(Math.hypot(...[0, 1, 2].map(k => g.position[k] - m.position[k])));
  const ng = Math.hypot(...g.rotation), nm = Math.hypot(...m.rotation);
  const dot = Math.abs(g.rotation.reduce((s, v, k) => s + v * m.rotation[k], 0)) / (ng * nm);
  dRot.push(2 * Math.acos(Math.min(1, dot)) * 180 / Math.PI);
  if (g.vertexCount !== m.vertexCountOriginal) vMismatch.push(`${g.id}: game ${g.vertexCount}, offline ${m.vertexCountOriginal}`);
  const mesh = meshes.get(g.id);
  if (mesh && mesh.kind === 0) {
    if (mesh.tris !== m.triangleCountOriginal) tMismatch.push(`${g.id}: game ${mesh.tris}, offline ${m.triangleCountOriginal}`);
    const d = Math.max(...[0, 1, 2].map(k => Math.max(Math.abs(mesh.mn[k] - m.boundsMin[k]), Math.abs(mesh.mx[k] - m.boundsMax[k]))));
    dBox.push(d); boxN++; boxWorst.push([d, g.id]);
  }
}
boxWorst.sort((a, b) => b[0] - a[0]);
