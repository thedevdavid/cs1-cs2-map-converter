// Cross-check the offline extraction against an in-game DakotaExport (v0.4.x) of the same map.
// Usage: node src/crosscheck.mjs <exportBase> <map.crp> <outDir>
//   exportBase: path prefix of the in-game export, e.g. %LOCALAPPDATA%/DakotaExport/2972879554_Dakota_Falls-20261019-063123
// Reads <outDir>/po-offline.json and po-offline-heights.png; writes <outDir>/crosscheck.md.
